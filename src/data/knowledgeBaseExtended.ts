// 获取神煞列表
export function getShenShaList(bazi: { year: string; month: string; day: string; hour: string }): string[] {
  const shenShaList: string[] = [];
  
  // 验证输入数据
  if (!bazi || !bazi.day || typeof bazi.day !== 'string') {
    return shenShaList;
  }
  
  const dayMaster = bazi.day.charAt(0);
  const dayBranch = bazi.day.charAt(1);
  
  // 验证日主干支
  if (!dayMaster || !dayBranch) {
    return shenShaList;
  }
  
  // 天乙贵人检查
  const tianYiMap: Record<string, string[]> = {
    '甲': ['丑', '未'],
    '乙': ['子', '申'],
    '丙': ['亥', '酉'],
    '丁': ['亥', '酉'],
    '戊': ['丑', '未'],
    '己': ['子', '申'],
    '庚': ['丑', '未'],
    '辛': ['寅', '午'],
    '壬': ['卯', '巳'],
    '癸': ['卯', '巳']
  };
  
  const tianYiBranches = tianYiMap[dayMaster] || [];
  const pillarsToCheck = [bazi.year, bazi.month, bazi.day, bazi.hour].filter((g): g is string => typeof g === 'string' && g.length >= 2);
  
  pillarsToCheck.forEach(ganZhi => {
    if (tianYiBranches.includes(ganZhi.charAt(1))) {
      if (!shenShaList.includes('天乙贵人')) {
        shenShaList.push('天乙贵人');
      }
    }
  });
  
  // 桃花检查
  const taoHuaMap: Record<string, string> = {
    '申': '酉', '子': '酉', '辰': '酉',
    '寅': '卯', '午': '卯', '戌': '卯',
    '巳': '午', '酉': '午', '丑': '午',
    '亥': '子', '卯': '子', '未': '子'
  };
  
  const taoHua = taoHuaMap[dayBranch];
  if (taoHua) {
    pillarsToCheck.forEach(ganZhi => {
      if (ganZhi.charAt(1) === taoHua) {
        if (!shenShaList.includes('桃花')) {
          shenShaList.push('桃花');
        }
      }
    });
  }
  
  // 文昌贵人检查
  const wenChangMap: Record<string, string> = {
    '甲': '巳', '乙': '午', '丙': '申', '丁': '酉', '戊': '申',
    '己': '酉', '庚': '亥', '辛': '子', '壬': '寅', '癸': '卯'
  };
  
  const wenChang = wenChangMap[dayMaster];
  if (wenChang) {
    pillarsToCheck.forEach(ganZhi => {
      if (ganZhi.charAt(1) === wenChang) {
        if (!shenShaList.includes('文昌贵人')) {
          shenShaList.push('文昌贵人');
        }
      }
    });
  }
  
  // 驿马检查
  const yiMaMap: Record<string, string> = {
    '申': '寅', '子': '寅', '辰': '寅',
    '寅': '申', '午': '申', '戌': '申',
    '巳': '亥', '酉': '亥', '丑': '亥',
    '亥': '巳', '卯': '巳', '未': '巳'
  };
  
  const yiMa = yiMaMap[dayBranch];
  if (yiMa) {
    pillarsToCheck.forEach(ganZhi => {
      if (ganZhi.charAt(1) === yiMa) {
        if (!shenShaList.includes('驿马')) {
          shenShaList.push('驿马');
        }
      }
    });
  }
  
  return shenShaList;
}

