// 获取建除十二神
export function getJianChu(dayZhi: string, monthZhi: string): string {
  const jianChuOrder = ['建', '除', '满', '平', '定', '执', '破', '危', '成', '收', '开', '闭'];
  const zhiOrder = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
  
  const monthIndex = zhiOrder.indexOf(monthZhi);
  const dayIndex = zhiOrder.indexOf(dayZhi);
  
  if (monthIndex === -1 || dayIndex === -1) return '平';
  
  const offset = (dayIndex - monthIndex + 12) % 12;
  return jianChuOrder[offset];
}

// 获取二十八宿
export function getXiu(dayZhi: string, dayGan: string): string {
  const xiuOrder = ['角', '亢', '氐', '房', '心', '尾', '箕', '斗', '牛', '女', '虚', '危', '室', '壁', '奎', '娄', '胃', '昴', '毕', '觜', '参', '井', '鬼', '柳', '星', '张', '翼', '轸'];
  const zhiOrder = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
  const ganOrder = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
  
  const zhiIndex = zhiOrder.indexOf(dayZhi);
  const ganIndex = ganOrder.indexOf(dayGan);
  
  if (zhiIndex === -1 || ganIndex === -1) return '角';
  
  const offset = (zhiIndex + ganIndex * 2) % 28;
  return xiuOrder[offset];
}

